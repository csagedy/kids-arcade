/* Dot-to-dot pictures. Each is a closed outline as [x, y] points in a 0..100
   square, in tapping order. Fewer points first. `color` fills the shape
   once every dot is joined.

   `details` (optional) dress the finished picture up, drawn in the same
   0..100 space. Widths and radii are in those units too, so they scale with
   the canvas. Each item is an array whose first entry is its kind:

     ['fill', color, [[x, y], ...]]       a second colour region; floods in
     ['disc', color, x, y, r]             a round colour region; floods in
     ['line', color, width, [[x, y], ...]] a stroke that draws itself on
     ['arc',  color, width, x, y, r, from, to]   ditto, angles in degrees
                                          (0 = right, 90 = down)
     ['dot',  color, x, y, r, ry?]        a spot that pops in
     ['star', color, x, y, r, points?]    a twinkly star that pops in
     ['eye',  x, y, r, 'big'?]            a cute eye that pops in and blinks

   Fills sit under the white outline; everything else is drawn on top. */

var DOT_INK = '#2b2140';            // eyes, mouths, whiskers
var DOT_CHEEK = 'rgba(255,90,140,0.45)';

/* A happy face: two eyes, a smile and rosy cheeks. */
function dotFace(x, y, size, opts) {
  opts = opts || {};
  var s = size / 10, out = [
    ['eye', x - 8 * s, y, 3.2 * s],
    ['eye', x + 8 * s, y, 3.2 * s],
    ['arc', DOT_INK, 1.5 * s, x, y + 4 * s, 6 * s, 25, 155]
  ];
  if (opts.cheeks !== false) out.unshift(['dot', DOT_CHEEK, x - 14 * s, y + 7 * s, 3.4 * s], ['dot', DOT_CHEEK, x + 14 * s, y + 7 * s, 3.4 * s]);
  return out;
}
/* A little bow (kite tail). */
function dotBow(color, x, y) {
  return ['fill', color, [[x - 5, y - 3.5], [x + 5, y + 3.5], [x + 5, y - 3.5], [x - 5, y + 3.5]]];
}

